    `active_guard` tinyint DEFAULT NULL COMMENT '进行中唯一占位，结束后必须释放为NULL',
    `web_user_id` bigint NOT NULL COMMENT '发起兑换的Web用户ID',
    `chat_id` bigint NOT NULL COMMENT '积分群/频道ID快照',
    `telegram_user_id` bigint NOT NULL COMMENT 'Telegram用户ID快照',
    `config_id` bigint NOT NULL COMMENT '兑换配置ID快照',
    `config_name` varchar(100) NOT NULL COMMENT '兑换配置名称快照',
    `redeem_type` varchar(32) NOT NULL COMMENT 'CREATE_ACCOUNT注册账号 RENEW续费',
    `redeem_days` int NOT NULL COMMENT '兑换天数快照',
