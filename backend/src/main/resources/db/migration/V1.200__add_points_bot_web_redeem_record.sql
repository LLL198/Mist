    `server_id` bigint NOT NULL COMMENT 'Emby服务器ID快照',
    `server_name` varchar(100) DEFAULT NULL COMMENT 'Emby服务器名称快照',
    `target_user_id` bigint DEFAULT NULL COMMENT '续费目标Web用户ID或新建用户ID',
    `target_user_name` varchar(100) DEFAULT NULL COMMENT '目标Emby用户名',
    `status` varchar(20) NOT NULL COMMENT 'PROCESSING SUCCESS REFUNDED',
    `result_message` varchar(255) DEFAULT NULL COMMENT '可向用户展示的处理结果',
    `expiration_date` datetime DEFAULT NULL COMMENT '兑换完成后的到期时间',
    `finished_at` datetime DEFAULT NULL COMMENT '处理完成时间',
